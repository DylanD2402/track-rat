#!/usr/bin/env python3
"""
Convert a logo image into include/logo_image.h for the start-up animation.

    pip install pillow
    python tools/png_to_logo.py my_logo.png                  # start-up logo, 280 px wide
    python tools/png_to_logo.py my_logo.png --height 20 --prefix LOGO_SM --out include/logo_small.h

Then rebuild and flash. To go back to the built-in placeholder logo, delete
include/logo_image.h.

- --width / --height scale to that size, keeping the aspect (give one or
  both; both fit inside the box). Without them, anything bigger than the
  screen is scaled down to fit.
- Transparent areas are flattened onto --bg (default black, the screen
  background), so the edges stay smooth.
- --prefix names the macros and array: PREFIX_W, PREFIX_H, PREFIX_PIXELS.
"""

import argparse
import os
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("This needs Pillow: pip install pillow")

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO_ROOT, "include", "logo_image.h")


def to_rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("image", help="logo image (.png, .jpg, ...)")
    ap.add_argument("--width", type=int, help="scale to this width (keeps the aspect)")
    ap.add_argument("--height", type=int, help="scale to this height (keeps the aspect)")
    ap.add_argument("--bg", default="000000", help="background hex colour to flatten onto (default 000000)")
    ap.add_argument("--prefix", default="LOGO", help="macro / array name prefix (default LOGO)")
    ap.add_argument("--out", default=OUT)
    args = ap.parse_args()

    img = Image.open(args.image).convert("RGBA")
    if args.width or args.height:
        scale = min((args.width or 10**6) / img.width, (args.height or 10**6) / img.height)
    else:
        scale = min(1.0, 320 / img.width, 240 / img.height)
    if scale != 1.0:
        size = (max(1, round(img.width * scale)), max(1, round(img.height * scale)))
        # premultiplied alpha so the edge doesn't pick up the colour hiding under transparent pixels
        img = img.convert("RGBa").resize(size, Image.LANCZOS).convert("RGBA")
    bgc = args.bg.lstrip("#")
    bg = Image.new("RGBA", img.size, (int(bgc[0:2], 16), int(bgc[2:4], 16), int(bgc[4:6], 16), 255))
    img = Image.alpha_composite(bg, img).convert("RGB")
    w, h = img.size

    px = [to_rgb565(*img.getpixel((x, y))) for y in range(h) for x in range(w)]
    lines = []
    for i in range(0, len(px), 12):
        lines.append("  " + ", ".join(f"0x{v:04X}" for v in px[i:i + 12]) + ",")

    with open(args.out, "w", newline="\n") as f:
        P = args.prefix
        f.write(f"// Generated by tools/png_to_logo.py from {os.path.basename(args.image)} (background #{bgc}).\n")
        f.write("#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\n\n")
        f.write(f"#define {P}_W {w}\n#define {P}_H {h}\n\n")
        f.write(f"const uint16_t {P}_PIXELS[{P}_W * {P}_H] PROGMEM = {{\n")
        f.write("\n".join(lines))
        f.write("\n};\n")
    print(f"Wrote {args.out}: {w} x {h} px, {w * h * 2 / 1024:.0f} KB. Rebuild and flash to see it.")


if __name__ == "__main__":
    main()
