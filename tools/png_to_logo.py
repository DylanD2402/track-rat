#!/usr/bin/env python3
"""
Convert a logo image into include/logo_image.h for the start-up animation.

    pip install pillow
    python tools/png_to_logo.py my_logo.png

Then rebuild and flash. To go back to the built-in placeholder logo, delete
include/logo_image.h.

- Any size works; anything bigger than the screen (320 x 240) is scaled
  down to fit. Around 240-300 px wide x 80-140 px tall looks best, and
  animates fastest.
- Transparent areas become black (the screen background).
- Bright colours on black look best on this display.
"""

import argparse
import os
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("This needs Pillow: pip install pillow")

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO_ROOT, "include", "logo_image.h")


def to_rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("image", help="logo image (.png, .jpg, ...)")
    ap.add_argument("--max-width", type=int, default=320)
    ap.add_argument("--max-height", type=int, default=240)
    ap.add_argument("--out", default=OUT)
    args = ap.parse_args()

    img = Image.open(args.image).convert("RGBA")
    if img.width > args.max_width or img.height > args.max_height:
        img.thumbnail((args.max_width, args.max_height), Image.LANCZOS)
    bg = Image.new("RGBA", img.size, (0, 0, 0, 255))
    img = Image.alpha_composite(bg, img).convert("RGB")
    w, h = img.size

    px = [to_rgb565(*img.getpixel((x, y))) for y in range(h) for x in range(w)]
    lines = []
    for i in range(0, len(px), 12):
        lines.append("  " + ", ".join(f"0x{v:04X}" for v in px[i:i + 12]) + ",")

    with open(args.out, "w") as f:
        f.write(f"// Generated by tools/png_to_logo.py from {os.path.basename(args.image)}. Delete to use the\n")
        f.write("// built-in placeholder logo.\n#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\n\n")
        f.write(f"#define LOGO_W {w}\n#define LOGO_H {h}\n\n")
        f.write("const uint16_t LOGO_PIXELS[LOGO_W * LOGO_H] PROGMEM = {\n")
        f.write("\n".join(lines))
        f.write("\n};\n")
    print(f"Wrote {args.out}: {w} x {h} px, {w * h * 2 / 1024:.0f} KB. Rebuild and flash to see it.")


if __name__ == "__main__":
    main()
